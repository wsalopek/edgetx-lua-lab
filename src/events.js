// Key / touch event constants for colour radios with PAGE keys and a rotary (TX16S, TX15, ...).
// Derived from EdgeTX radio/src/keys.h, hal/key_driver.h and util/hw_defs/lua_keys.jinja.
const KEY = { MENU: 0, EXIT: 1, ENTER: 2, PAGEUP: 3, PAGEDN: 4, UP: 5, DOWN: 6, LEFT: 7, RIGHT: 8, PLUS: 9, MINUS: 10, MODEL: 11, TELE: 12, SYS: 13, SHIFT: 14, BIND: 15 };
const BREAK = 0x0200, REPT = 0x0400, FIRST = 0x0600, LONG = 0x0800;
const VIRTUAL = 0x2000, ROT_LEFT = 0x1003, ROT_RIGHT = 0x1004;
const T = VIRTUAL | 't'.charCodeAt(0);

export const EVENTS = {
  EVT_VIRTUAL_PREV: ROT_LEFT, EVT_VIRTUAL_NEXT: ROT_RIGHT, EVT_VIRTUAL_DEC: ROT_LEFT, EVT_VIRTUAL_INC: ROT_RIGHT,
  EVT_ROT_LEFT: ROT_LEFT, EVT_ROT_RIGHT: ROT_RIGHT,
  EVT_VIRTUAL_PREV_PAGE: KEY.PAGEUP | BREAK, EVT_VIRTUAL_NEXT_PAGE: KEY.PAGEDN | BREAK,
  EVT_VIRTUAL_MENU: KEY.MODEL | BREAK, EVT_VIRTUAL_MENU_LONG: KEY.MODEL | LONG,
  EVT_VIRTUAL_ENTER: KEY.ENTER | BREAK, EVT_VIRTUAL_ENTER_LONG: KEY.ENTER | LONG,
  EVT_VIRTUAL_EXIT: KEY.EXIT | BREAK, EVT_EXIT_BREAK: KEY.EXIT | BREAK,
  EVT_TOUCH_FIRST: T | FIRST, EVT_TOUCH_BREAK: T | BREAK, EVT_TOUCH_SLIDE: T | LONG, EVT_TOUCH_TAP: T | REPT,
};
for (const [name, k] of [['ENTER', KEY.ENTER], ['ROT', KEY.ENTER], ['TELEM', KEY.TELE], ['MODEL', KEY.MODEL], ['SYS', KEY.SYS], ['PAGEUP', KEY.PAGEUP], ['PAGEDN', KEY.PAGEDN]]) {
  EVENTS[`EVT_${name}_FIRST`] = k | FIRST; EVENTS[`EVT_${name}_BREAK`] = k | BREAK; EVENTS[`EVT_${name}_LONG`] = k | LONG; EVENTS[`EVT_${name}_REPT`] = k | REPT;
}
export const isTouch = (e) => (e & ~0x0e00) === T;

// Buttons the simulator offers (label -> event sent when pressed; "long" = held)
export const KEYS = {
  ENTER: EVENTS.EVT_VIRTUAL_ENTER, EXIT: EVENTS.EVT_VIRTUAL_EXIT, 'PAGE<': EVENTS.EVT_VIRTUAL_PREV_PAGE, 'PAGE>': EVENTS.EVT_VIRTUAL_NEXT_PAGE,
  MDL: EVENTS.EVT_VIRTUAL_MENU, TELE: EVENTS.EVT_TELEM_BREAK, SYS: EVENTS.EVT_SYS_BREAK, 'wheel <': ROT_LEFT, 'wheel >': ROT_RIGHT,
};
